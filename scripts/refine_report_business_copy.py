def text(node):
    return "".join(node.xpath(".//w:t/text()", namespaces=NS))

def replace(node, value):
    leaves = node.xpath(".//w:t", namespaces=NS)
    if not leaves:
        raise ValueError("Paragraph contains no text runs")
    # Keep the emphasis on the decision label and retain all existing run properties.
    if value.startswith("投放判断  ") and len(leaves) >= 3:
        leaves[0].text, leaves[1].text, leaves[2].text = "投放判断", "  ", value.split("  ", 1)[1]
        leaves = leaves[3:]
    else:
        leaves[0].text = value
        leaves = leaves[1:]
    for leaf in leaves:
        leaf.text = ""
    for leaf in node.xpath(".//w:t", namespaces=NS):
        leaf.set(XML_SPACE, "preserve")

def revise(source, output):
    with ZipFile(source) as archive:
        root = etree.fromstring(archive.read("word/document.xml"))
        paragraphs = root.xpath("./w:body/w:p", namespaces=NS)
        for index, (opening, value) in COPY.items():
            if not text(paragraphs[index]).startswith(opening):
                raise ValueError(f"Source changed at paragraph {index}; review before applying")
            replace(paragraphs[index], value)

        for p in root.xpath("//w:p", namespaces=NS):
            current = text(p)
            if current in HEADINGS:
                replace(p, HEADINGS[current])
            else:
                # TOC chapter titles contain fields and tabs, which must survive.
                for old, new in HEADINGS.items():
                    if current.startswith(old) and p.xpath(".//w:fldChar", namespaces=NS):
                        for t in p.xpath(".//w:t", namespaces=NS):
                            if t.text and old in t.text:
                                t.text = t.text.replace(old, new)

        tables = root.xpath("./w:body/w:tbl", namespaces=NS)
        updates = {
            (0, 4, 2): "是否收到短信、是否购买",
            (1, 1, 2): "了解客户、估计效果、建立选客方案",
            (1, 2, 2): "按同样覆盖比例筛选候选方案",
            (1, 3, 2): "用未参与选型的客户检验推广条件",
            (5, 1, 1): "短信组购买率减去对照组购买率，再乘以 100。差值 3.32 个百分点，相当于每 1,000 位客户约多 33 位购买者；能否归因于短信需核实分组方式。",
            (5, 2, 1): "模型选中名单内的购买率差，减去基准名单内的购买率差。用于判断换用选客方式的收益，统计时考虑两份名单的客户重叠。",
            (5, 3, 1): "汇总覆盖不同比例客户时的排序效果。AUUC 衡量效果曲线的面积；Qini 衡量累计增量表现超出随机参考线的面积。统一口径下数值越高，通常表示排序更有效，仍需结合独立检验和投放成本。",
        }
        for (table, row, col), value in updates.items():
            cell = tables[table].findall(W+"tr")[row].findall(W+"tc")[col]
            replace(cell.find(W+"p"), value)

        output.parent.mkdir(parents=True, exist_ok=True)
        with ZipFile(output, "w") as final:
            for item in archive.infolist():
                data = etree.tostring(root, xml_declaration=True, encoding="UTF-8", standalone=True) if item.filename == "word/document.xml" else archive.read(item.filename)
                final.writestr(item, data)

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    revise(args.source, args.output)
